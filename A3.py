a = input("Enter brand colour: ").lower()
if a == "black" :
	print("Digit = 0")
elif a == "brown" :
	print("Digit = 1")
elif a == "red" :
	print("Digit = 2")
elif a == "orange" :
	print("Digit = 3")
elif a == "yellow" :
	print("Digit = 4")
elif a == "green" :
	print("Digit = 5")
elif a == "blue" :
	print("Digit = 6")
elif a == "violet" :
	print("Digit = 7")
elif a == "grey" :
	print("Digit = 8")
elif a == "white" :
	print("Digit = 9")
else :
	print("Invalid colour")